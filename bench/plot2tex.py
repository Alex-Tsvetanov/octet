#!/usr/bin/env python3
"""Writes the from-thread-start effects of two benchmark runs as TikZ macros for the slides.

    plot2tex.py WINDOWS_RUN_DIR LINUX_RUN_DIR OUT_FILE

analyse.py prints numbers with a decimal comma for the Bulgarian text, which TikZ cannot
read as a coordinate. This script reads the same summary.json files and writes plain
decimals, so the chart in the slides is drawn from the evidence and not typed by hand.
"""

import json
import os
import sys


def effects(run_dir):
    path = os.path.join(run_dir, "summary.json")
    with open(path, encoding="utf-8") as f:
        summary = json.load(f)
    try:
        return summary["effects"]["from_thread_start"]
    except KeyError:
        sys.exit(f"{path}: no from_thread_start effects; run bench/analyse.py first")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    runs = {"win": effects(sys.argv[1]), "lin": effects(sys.argv[2])}
    lines = ["% Generated by bench/plot2tex.py. Do not edit by hand."]
    for platform, arms in runs.items():
        for wire in ("tls", "clear"):
            e = arms[wire]
            name = f"{platform}{wire.capitalize()}"
            lines.append(f"\\def\\plot{name}Diff{{{e['diff_p50_us']:.1f}}}")
            lines.append(f"\\def\\plot{name}Low{{{e['ci_low']:.1f}}}")
            lines.append(f"\\def\\plot{name}High{{{e['ci_high']:.1f}}}")
    with open(sys.argv[3], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
