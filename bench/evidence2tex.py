#!/usr/bin/env python3
"""Turns the micro-benchmark outputs and the test logs in evidence/ into LaTeX macros.

    evidence2tex.py EVIDENCE_DIR OUT_FILE

So that no number the course project quotes from them is typed by hand. Fails loudly if
a file is missing or the two platforms disagree on a check count.
"""

import glob
import os
import re
import sys


def num(x, digits=1):
    return f"{x:.{digits}f}".replace(".", "{,}")


def micro(path):
    text = open(path, encoding="utf-8").read()
    out = {}
    for name in ("dedicated", "detecting"):
        m = re.search(rf"^{name}\s+ns per connection: median ([0-9.]+)", text, re.M)
        if not m:
            sys.exit(f"{path}: no {name} line")
        out[name] = float(m.group(1))
    out["diff"] = out["detecting"] - out["dedicated"]
    m = re.search(r"^rounds (\d+), iterations per round (\d+)", text, re.M)
    out["rounds"], out["iterations"] = int(m.group(1)), int(m.group(2))
    m = re.search(r"commit (\w+)", text)
    out["commit"] = m.group(1) if m else ""
    return out


def tests(path):
    text = open(path, encoding="utf-8").read()
    suites = {name: int(n) for name, n in re.findall(r"\b(classify|replay|http|tls): (\d+) checks, 0 failed", text)}
    m = re.search(r"(\d+)/(\d+) passed", text)
    if len(suites) != 4 or not m or m.group(1) != m.group(2):
        sys.exit(f"{path}: not a clean run")
    suites["integration"] = int(m.group(2))
    return suites


def latest(evidence, pattern):
    files = sorted(glob.glob(os.path.join(evidence, pattern)))
    if not files:
        sys.exit(f"nothing matches {pattern}")
    return files[-1]


def main():
    evidence, out_path = sys.argv[1], sys.argv[2]
    lines = ["% Generated by bench/evidence2tex.py. Do not edit by hand."]

    def macro(name, value):
        lines.append("\\newcommand{\\" + name + "}{" + str(value) + "}")

    for tag, pattern in (("Win", "*_micro_windows.txt"), ("Lin", "*_micro_linux.txt")):
        m = micro(latest(evidence, pattern))
        macro(f"micro{tag}Dedicated", num(m["dedicated"]))
        macro(f"micro{tag}Detecting", num(m["detecting"]))
        macro(f"micro{tag}Diff", num(m["diff"]))
        macro(f"micro{tag}Rounds", m["rounds"])
        macro(f"micro{tag}Iterations", m["iterations"])

    win = tests(latest(evidence, "*_tests_windows.log"))
    lin = tests(latest(evidence, "*_tests_linux.log"))
    if win != lin:
        sys.exit(f"check counts differ between platforms: {win} {lin}")
    for name, count in win.items():
        macro("checks" + name.capitalize(), count)
    macro("checksUnitTotal", sum(v for k, v in win.items() if k != "integration"))

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
